require('./purchase-orders.test.cjs');
const assert=require('node:assert/strict');
const {orderChanges,orderActor}=require('../lib/order-history.ts');
const {blankOrder,blankItem}=require('../lib/purchase-orders.ts');
const first={revision:1,action:'created',actor_snapshot:{full_name:'Persona QA',username:'qa'},snapshot:{order:{...blankOrder('pcp'),tax:'16',subtotal:'100',total:'116'},items:[{...blankItem(),description:'Pieza',quantity:'1'}]}};
const second=structuredClone(first);second.revision=2;second.action='updated';second.snapshot.order.notes='Entregar por la tarde';second.snapshot.items[0].quantity='2';
assert.ok(orderChanges(second,first).some(v=>v.includes('Cantidad: 1 → 2')));
assert.ok(orderChanges(second,first).some(v=>v.includes('Observaciones:')));
assert.equal(orderActor(first),'Persona QA (@qa)');
assert.equal(orderActor({action:'kind_migrated'}),'Sistema');
assert.equal(orderActor({action:'updated'}),'Usuario no disponible');
const same=structuredClone(first);same.revision=2;same.action='updated';same.snapshot.items[0].quantity='1.0000';
assert.deepEqual(orderChanges(same,first),['Sin cambios en los datos de la orden.']);
assert.match(orderChanges(second)[0],/No está disponible/);
const added=structuredClone(second);added.snapshot.items.push({...blankItem(),description:'Servicio'});
assert.ok(orderChanges(added,first).some(v=>v.includes('Partida 2 agregada')));
const removed=structuredClone(second);removed.revision=3;
assert.ok(orderChanges(removed,added).some(v=>v.includes('Partida 2 eliminada')));
console.log('PASS: history field changes, numeric normalization, actors and missing predecessor.');
