require('./purchase-orders.test.cjs');
const assert=require('node:assert/strict');
const {blankItem,blankOrder,validateOrder}=require('../lib/purchase-orders.ts');
const {orderChanges}=require('../lib/order-history.ts');
const a={...blankItem(),kind:'service',description:'A',commitment_date:'2026-10-15'};
const b={...a,id:crypto.randomUUID(),description:'B'};
const order={...blankOrder('pcp'),number:'QA',client_id:'qa',items:[a,b]};
assert.notEqual(blankItem().id,blankItem().id);
assert.equal(validateOrder(order).items[0].id,a.id);
for(const items of [[a,a],[{...a,id:''}],[{...a,id:'bad'}]])assert.throws(()=>validateOrder({...order,items}));
assert.equal(validateOrder({...order,items:[{...a,operations_locked_at:'fake'}]}).items[0].operations_locked_at,undefined);
const previous={revision:1,action:'created',snapshot:{order,items:[a,b]}};
const next={revision:2,action:'updated',snapshot:{order,items:[{...b,quantity:'2'}]}};
const changes=orderChanges(next,previous);
assert.ok(changes.includes('Partida 1 eliminada: A'));
assert.ok(changes.some(v=>v.includes('Partida 2 movida a la posición 1')));
assert.ok(changes.some(v=>v.includes('Cantidad: 1 → 2')));
assert.ok(!changes.some(v=>v.includes('Descripción: A')));
const legacy=structuredClone(previous);delete legacy.snapshot.items[0].id;delete legacy.snapshot.items[1].id;
assert.ok(orderChanges({...next,snapshot:{order,items:[a,b]}},legacy).includes('Sin cambios en los datos de la orden.'));
console.log('PASS: stable IDs, duplicates, read-only locks, history by identity and legacy fallback');
