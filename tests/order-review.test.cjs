const assert=require('node:assert/strict'),fs=require('node:fs'),swc=require('next/dist/build/swc');
require.extensions['.ts']=(m,f)=>m._compile(swc.transformSync(fs.readFileSync(f,'utf8'),{filename:f,jsc:{parser:{syntax:'typescript'},target:'es2020'},module:{type:'commonjs'}}).code,f);
const {summarizeOrderWarnings}=require('../lib/order-review.ts');
const {blankOrder,blankItem,orderReviewWarnings}=require('../lib/purchase-orders.ts');
const warnings=Array.from({length:30},(_,i)=>`PolloQro, partida ${i+1} (página ${i<15?1:2}): se intercambiaron CANT. y UNITARIO por posible inversión de columnas. Cantidad: ${1000+i}.00 → 1.00; precio unitario: 1.00 → ${1000+i}.00. El importe se conserva; favor de verificar en el documento.`);
const original=[...warnings];
assert.equal(summarizeOrderWarnings(warnings).length,1);
assert.ok(summarizeOrderWarnings(warnings)[0].endsWith('Partidas '+Array.from({length:30},(_,i)=>i+1).join(', ')+'.'));
assert.deepEqual(warnings,original);
assert.deepEqual(summarizeOrderWarnings(['Aviso general','Aviso general']),['Aviso general']);
assert.equal(summarizeOrderWarnings(['Partida 1: problema A.','Partida 2: problema B.']).length,2);
assert.deepEqual(summarizeOrderWarnings(['Partida 10: problema.','Partida 2: problema.','Partida 2: problema.']),['Problema. Partidas 2, 10.']);
const draft=blankOrder('pcp');draft.revision=1;draft.order_date='2026-10-13';
draft.items=Array.from({length:30},()=>blankItem());
assert.equal(orderReviewWarnings(draft).length,1);
draft.items[0].commitment_date='2026-10-01';draft.items[1].commitment_date='2026-10-02';
const grouped=orderReviewWarnings(draft);
assert.equal(grouped.length,2);
assert.ok(grouped[0].endsWith('Partidas 1, 2.'));
assert.ok(grouped[1].includes('Partidas 3, 4, 5'));
assert.deepEqual(orderReviewWarnings(blankOrder('pcp')),[]);
console.log('PASS: repeated review warnings, all affected positions, distinct issues and original details preserved.');
