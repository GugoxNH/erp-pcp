require('./purchase-orders.test.cjs');
const assert=require('node:assert/strict');
const {newPurchase,validatePurchase,stockQuantity,purchaseTotal}=require('../lib/purchases.ts');
const p=newPurchase('pcp');
p.supplier_id=crypto.randomUUID();p.number='QA';p.tax='16';
p.items[0].product_id=crypto.randomUUID();p.items[0].quantity='10';p.items[0].unit_price='10';
p.items[0].allocations=[{item_id:crypto.randomUUID(),quantity:'4'}];
assert.equal(stockQuantity(p.items[0]),'6');
assert.equal(purchaseTotal(p),'116.00');
assert.equal(validatePurchase(p).number,'QA');
assert.throws(()=>validatePurchase({...p,items:[]}));
assert.throws(()=>validatePurchase({...p,date:'2026-02-30'}));
assert.throws(()=>validatePurchase({...p,number:''}));
assert.throws(()=>validatePurchase({...p,items:[{...p.items[0],quantity:'3'}]}));
assert.throws(()=>validatePurchase({...p,items:[{...p.items[0],allocations:[...p.items[0].allocations,...p.items[0].allocations]}]}));
assert.throws(()=>validatePurchase({...p,items:[{...p.items[0],unit_price:'-1'}]}));
console.log('PASS: purchase validation, totals, stock remainder and duplicate destinations');
const {purchaseAutomaticTax}=require('../lib/purchases.ts');
assert.equal(purchaseAutomaticTax(p.items),'16.00');
assert.equal(purchaseAutomaticTax([{...p.items[0],quantity:'2',unit_price:'125.50'}]),'40.16');
assert.equal(purchaseAutomaticTax([{...p.items[0],quantity:'3',unit_price:'0.3333'}]),'0.16');
assert.equal(purchaseAutomaticTax([]),'0.00');
assert.throws(()=>purchaseAutomaticTax([{...p.items[0],unit_price:''}]));
assert.throws(()=>purchaseAutomaticTax([{...p.items[0],quantity:'-1'}]));
assert.equal(purchaseTotal({...p,tax:'5'}),'105.00');
console.log('PASS: automatic 16 percent tax, rounding and manual override');
